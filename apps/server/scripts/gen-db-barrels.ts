// scripts/gen-db-barrels.ts
import { readdirSync, writeFileSync } from "node:fs";

const HEADER = "// AUTO-GENERATED by scripts/gen-db-barrels.ts. Do not edit.\n";
const tsFiles = (dir: string) =>
  readdirSync(dir)
    .filter((f) => f.endsWith(".ts") && f !== "index.ts" && !f.startsWith("_"))
    .map((f) => f.replace(/\.ts$/, ""))
    .sort();

// schema/index.ts: plain re-exports
const tables = tsFiles("configs/database/schema");
writeFileSync(
  "configs/database/schema/index.ts",
  HEADER + tables.map((n) => `export * from "./${n}";`).join("\n") + "\n",
);

// relations/index.ts: import each part and merge into one typed object
const parts = tsFiles("configs/database/relations");
writeFileSync(
  "configs/database/schema/index.ts",
  HEADER +
    `import { defineRelations } from "drizzle-orm";\n` +
    `import * as schema from "../schema";\n` +
    parts.map((n) => `import ${n} from "./${n}";`).join("\n") +
    `\n\nexport const relations = {\n` +
    `  ...defineRelations(schema, () => ({})),\n` +
    parts.map((n) => `  ...${n},`).join("\n") +
    `\n};\n`,
);
